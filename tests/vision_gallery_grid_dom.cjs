const assert = require('node:assert/strict');
const path = require('node:path');
const { createRequire } = require('node:module');
const project = path.resolve(__dirname, '..');
const esbuild = require(project + '/node_modules/esbuild');
const dependency = createRequire(path.resolve(process.env.JSDOM_PACKAGE_ROOT, 'package.json'));
const { JSDOM, VirtualConsole } = dependency('jsdom');

async function check() {
  const built = await esbuild.build({ stdin: { contents: "import React from 'react'; import {createRoot} from 'react-dom/client'; import {MultimodalLab} from './src/MultimodalLab'; createRoot(document.getElementById('root')).render(React.createElement(MultimodalLab));", resolveDir: project }, bundle: true, write: false, format: 'iife', loader: { '.css': 'empty' }, define: { 'process.env.NODE_ENV': '"production"' } });
  const cases = Array.from({ length: 11 }, (_, index) => ({ id: `case-${index}`, title: `构造案例 ${index}`, question: '只用于隔离测试的构造问题', suite: 'public', assetId: `asset-${index}`, assetHash: `hash-${index}`, expectedRoute: 'self_service', topic: index < 3 ? '前3组' : '其他', imageAvailable: index !== 10 }));
  cases.push({ ...cases[0], id: 'same-image-question', title: '同图不同问题' });
  cases.push({ ...cases[1], id: 'same-image-another', title: '另一条同图问题' });
  const errors = [];
  const proxy = new VirtualConsole();
  proxy.on('jsdomError', error => errors.push(error.message));
  const dom = new JSDOM('<!doctype html><html><body><div id="root"></div></body></html>', { url: 'http://127.0.0.1:4296/#compare?mode=vision', runScripts: 'dangerously', pretendToBeVisual: true, virtualConsole: proxy });
  const window = dom.window;
  const document = window.document;
  window.fetch = async (input, options) => {
    assert.ok(!options?.method || options.method === 'GET');
    const target = new URL(input, window.location.href);
    assert.equal(target.origin, window.location.origin);
    if (target.pathname.endsWith('/multimodal/state')) return new Response(JSON.stringify({ cases, runs: [], inventory: { public: 12 } }));
    if (target.pathname.endsWith('/lab/state')) return new Response(JSON.stringify({ versions: [], connections: [] }));
    if (target.pathname.includes('/assets/')) return new Response(JSON.stringify({ width: 1, height: 1, dataUrl: 'data:image/png;base64,', privacy: {} }));
    throw new Error('Unexpected request');
  };
  window.matchMedia = () => ({ matches: false, addEventListener() {}, removeEventListener() {} });
  window.ResizeObserver = class { observe() {} unobserve() {} disconnect() {} };
  window.scrollTo = () => {};
  window.HTMLElement.prototype.scrollIntoView = () => {};
  window.eval(built.outputFiles[0].text);
  const wait = async predicate => { const deadline = Date.now() + 10000; while (Date.now() < deadline) { if (predicate()) return; await new Promise(resolve => setTimeout(resolve, 25)); } throw new Error('Timed out: ' + predicate.toString()); };
  const button = name => [...document.querySelectorAll('button')].find(element => element.textContent.trim() === name);
  const cards = () => [...document.querySelectorAll('.mm-case')];
  const groups = () => cards().map(element => element.dataset.imageGroup);
  const fill = (element, value) => { const prototype = element.tagName === 'SELECT' ? window.HTMLSelectElement.prototype : window.HTMLInputElement.prototype; Object.getOwnPropertyDescriptor(prototype, 'value').set.call(element, value); element.dispatchEvent(new window.Event(element.tagName === 'SELECT' ? 'change' : 'input', { bubbles: true })); };
  try {
    await wait(() => cards().length === 9);
    assert.ok(document.querySelector('.mm-gallery-summary').textContent.includes('13 个案例 · 11 个图片组'));
    const firstPage = groups();
    cards()[0].querySelector('input').click();
    button('下一页图片').click();
    await wait(() => cards().length === 2);
    assert.ok(groups().every(group => !firstPage.includes(group)));
    assert.equal(button('下一页图片').disabled, true);
    assert.equal(cards()[1].querySelector('input').disabled, true);
    cards()[0].querySelector('input').click();
    button('上一页图片').click();
    await wait(() => cards().length === 9);
    assert.equal(cards()[0].querySelector('input').checked, true);
    fill(document.querySelector('[aria-label="选择图片组数"]'), '10');
    button('每组选择一例').click();
    await wait(() => document.querySelector('.lab-selection').textContent.includes('已选 10 / 12 例'));
    assert.equal(document.querySelectorAll('.mm-case input:checked').length, 9);
    cards()[0].querySelector('.mm-photo-button').click();
    await wait(() => document.querySelector('[role=dialog]'));
    const options = document.querySelector('[aria-label="同类案例"]');
    assert.equal(options.options.length, 2);
    fill(options, 'same-image-question');
    await wait(() => document.querySelector('[aria-label="选择当前预览案例"]').checked === false);
    document.querySelector('[aria-label="选择当前预览案例"]').click();
    document.querySelector('[aria-label="关闭窗口"]').click();
    await wait(() => !document.querySelector('[role=dialog]'));
    assert.ok(cards()[0].textContent.includes('已选 2 例'));
    button('清空选择').click();
    await wait(() => !button('清空选择'));
    [...document.querySelectorAll('[aria-label="图片案例场景分类"] button')].find(element => element.textContent.startsWith('前3组')).click();
    await wait(() => cards().length === 3);
    assert.equal(button('下一页图片'), undefined);
    assert.equal(document.querySelector('[aria-label="选择图片组数"]').max, '3');
    fill(document.querySelector('[aria-label="选择图片组数"]'), '4');
    assert.equal(button('每组选择一例').disabled, true);
    assert.equal(button('开始同批图文评测').disabled, true);
    assert.deepEqual(errors, []);
    console.log('PASS: 9+2 pagination, no repeated groups, cross-page selection, same-image variant selection, missing image disabled, count bounds, classification resets, clear selection, no paid calls');
  } finally { window.close(); }
}
check().catch(error => { console.error(error); process.exitCode = 1; });
