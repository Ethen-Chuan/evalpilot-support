const assert = require('node:assert/strict');
const path = require('node:path');
const { createRequire } = require('node:module');
const project = path.resolve(__dirname, '..');
const dependencies = createRequire(path.resolve(process.env.JSDOM_PACKAGE_ROOT, 'package.json'));
const { JSDOM, VirtualConsole } = dependencies('jsdom');
const esbuild = require(project + '/node_modules/esbuild');

async function check() {
  const built = await esbuild.build({ stdin: { contents: `import React from 'react'; import {createRoot} from 'react-dom/client'; import {Theme} from '@radix-ui/themes'; import {AgentLab} from './src/AgentLab'; const root=createRoot(document.getElementById('root')); root.render(<Theme><AgentLab view="runs" corpora={[]}/></Theme>);`, resolveDir: project, loader: 'tsx' }, bundle: true, write: false, format: 'iife', loader: { '.css': 'empty' }, define: { 'process.env.NODE_ENV': '"production"' } });
  const errors = [];
  const calls = [];
  const consoleProxy = new VirtualConsole();
  consoleProxy.on('jsdomError', error => errors.push(error.message));
  const dom = new JSDOM('<!doctype html><html><body><div id="root"></div></body></html>', { url: 'http://127.0.0.1:4295/#benchmark?run=EVAL-QUALITY-FIXTURE', runScripts: 'dangerously', pretendToBeVisual: true, virtualConsole: consoleProxy });
  const window = dom.window;
  const document = window.document;
  const version = { id: 'MODEL-FIXTURE', name: '隔离测试模型', kind: 'external', provider: 'fixture', model: 'fixture-model', connectionId: 'fixture-connection' };
  const baseRow = { caseId: 'case-0', sessionId: 'session-fixture', versionId: version.id, traceId: 'trace-fixture', expectedIntent: 'fault_repair', expectedAction: 'clarify', status: 'completed', intentMatch: true, actionMatch: true, latencyMs: 1234, output: { intent: 'fault_repair', action: 'handoff', answer: '隔离构造答复，请核对当前设备。<img src=x onerror=alert(1)>' } };
  const judgment = { dimensions: { relevance: 4, next_step: 3, boundary: 4 }, reason: '隔离裁判认为建议基本合理', evidenceIds: ['user-fixture', 'candidate'] };
  const rows = [baseRow, { ...baseRow, caseId: 'case-1', judgment, intentMatch: false, actionMatch: false }, { ...baseRow, caseId: 'case-2', judgment: { ...judgment, dimensions: { relevance: 4, next_step: 1, boundary: 4 }, reason: '隔离裁判指出下一步缺少依据' } }, { ...baseRow, caseId: 'case-3', judgment: { ...judgment, dimensions: { relevance: 4, next_step: null, boundary: 4 } } }, { ...baseRow, caseId: 'case-4', judgeError: '隔离裁判读取失败' }, { ...baseRow, caseId: 'case-5', status: 'failed', output: undefined }];
  const cases = Array.from({ length: 25 }, (_, index) => ({ id: `case-${index}`, sessionId: `session-${index}`, title: '匿名构造案例', question: '设备没有显示画面怎么办？', intent: 'fault_repair', action: 'clarify', prefix: [{ id: 'user-fixture', role: 'user', sequence: 1, content: '隔离用户问设备没有画面', metadata: {} }], reference: { id: 'human-fixture', role: 'human', sequence: 2, content: '隔离人工回复：请提供型号', metadata: {} } }));
  const bundle = { id: 'bundle-fixture', datasetId: 'project-fixture', splits: { test: 25 } };
  const run = { id: 'EVAL-QUALITY-FIXTURE', bundleId: bundle.id, status: 'completed', createdAt: '2026-10-23T00:00:00Z', completed: rows.length, total: rows.length, caseHash: 'fixture-hash', protocol: 'fixture', models: [version], metrics: {}, results: rows, caseIds: rows.map(row => row.caseId), judgeId: null };
  const state = { bundles: [bundle], versions: [version], connections: [{ id: 'fixture-connection', name: '已配置的测试裁判', provider: 'fixture', candidateModel: 'fixture-model', judgeModel: 'fixture-judge', endpoint: 'https://example.invalid', configured: true, tested: true }], runs: [run], training: [], intents: { fault_repair: '故障维修' }, actions: { clarify: '澄清与补充信息', handoff: '升级人工核实' } };
  let failCase = false;
  let delayCase = false;
  let releaseCase;
  window.fetch = async (input, options) => {
    const target = new URL(input, window.location.href);
    assert.equal(target.origin, window.location.origin);
    assert.equal(options?.method || 'GET', 'GET', 'No inference or mutation request is allowed');
    calls.push(target.pathname);
    let payload;
    if (target.pathname.endsWith('/state')) payload = state;
    else if (target.pathname.includes('/runs/')) payload = run;
    else if (target.pathname.endsWith('/cases')) payload = cases;
    else if (target.pathname.includes('/case/')) {
      if (failCase) return new Response(JSON.stringify({ error: 'fixture failure' }), { status: 503 });
      const identifier = decodeURIComponent(target.pathname.split('/').at(-1));
      payload = cases.find(item => item.id === identifier);
      if (delayCase) { delayCase = false; return new Promise(resolve => { releaseCase = () => resolve(new Response(JSON.stringify(payload))); }); }
    } else throw new Error('Unexpected request ' + target.pathname);
    return new Response(JSON.stringify(payload));
  };
  window.matchMedia = () => ({ matches: false, addEventListener() {}, removeEventListener() {} });
  window.ResizeObserver = class { observe() {} unobserve() {} disconnect() {} };
  window.eval(built.outputFiles[0].text);
  const wait = async predicate => { const deadline = Date.now() + 8000; while (Date.now() < deadline) { if (predicate()) return; await new Promise(resolve => setTimeout(resolve, 25)); } throw new Error('Timed out: ' + predicate); };
  const button = (name, scope = document) => [...scope.querySelectorAll('button')].find(element => element.textContent.trim() === name || element.getAttribute('aria-label') === name);
  const field = label => document.querySelector(`[aria-label="${label}"]`);
  const fill = (element, value) => { const prototype = element.tagName === 'SELECT' ? window.HTMLSelectElement.prototype : window.HTMLInputElement.prototype; Object.getOwnPropertyDescriptor(prototype, 'value').set.call(element, value); element.dispatchEvent(new window.Event(element.tagName === 'SELECT' ? 'change' : 'input', { bubbles: true })); };
  const tableRows = () => [...document.querySelectorAll('.reply-results-table tbody tr')];
  try {
    await wait(() => tableRows().length === 6);
    assert.ok(!document.querySelector('.reply-results-table thead').textContent.includes('意图'));
    assert.equal(tableRows()[0].dataset.reviewStatus, 'unreviewed');
    assert.equal(tableRows()[1].dataset.reviewStatus, 'reasonable');
    assert.equal(document.querySelectorAll('.reply-results-table img').length, 0);
    fill(field('答复评审筛选'), 'attention');
    await wait(() => tableRows().length === 1);
    assert.equal(tableRows()[0].dataset.reviewStatus, 'attention');
    fill(field('答复评审筛选'), 'unreviewed');
    await wait(() => tableRows().length === 3);
    fill(field('搜索答复、模型或案例编号'), '不存在的搜索项');
    await wait(() => button('显示全部结果'));
    button('显示全部结果').click();
    await wait(() => tableRows().length === 6);
    button('查看对话与结果', tableRows()[1]).click();
    await wait(() => document.querySelector('.reply-evidence-workspace .conversation-playback'));
    assert.equal(document.querySelector('.reply-diagnostics').open, false);
    assert.equal(document.querySelector('.reply-review-scores').textContent.includes('4 / 4'), true);
    document.querySelector('.reply-review-evidence summary').click();
    assert.ok(document.querySelector('.reply-review-evidence').textContent.includes('隔离用户问设备没有画面'));
    assert.equal(document.querySelector('.reply-review-evidence img'), null);
    document.querySelector('.reply-diagnostics summary').click();
    assert.ok(document.querySelector('.reply-diagnostics').textContent.includes('升级人工核实'));
    assert.ok(document.querySelector('.reply-diagnostics').textContent.includes('澄清与补充信息'));
    assert.ok(document.querySelector('.reply-diagnostics').textContent.includes('与参考不同'));
    assert.ok(document.querySelector('.reply-diagnostics').textContent.includes('隔离人工回复：请提供型号'));
    button('关闭窗口').click();
    await wait(() => !document.querySelector('[role=dialog]'));
    failCase = true;
    button('查看对话与结果', tableRows()[0]).click();
    await wait(() => button('重试案例证据'));
    assert.ok(document.querySelector('.reply-review').textContent.includes('未评审'));
    failCase = false;
    button('重试案例证据').click();
    await wait(() => document.querySelector('.reply-evidence-workspace .conversation-playback'));
    button('关闭窗口').click();
    await wait(() => !document.querySelector('[role=dialog]'));
    delayCase = true;
    button('查看对话与结果', tableRows()[0]).click();
    await wait(() => releaseCase);
    button('关闭窗口').click();
    await wait(() => !document.querySelector('[role=dialog]'));
    button('查看对话与结果', tableRows()[1]).click();
    await wait(() => document.querySelector('.reply-record-ids')?.textContent.includes('case-1'));
    releaseCase();
    await new Promise(resolve => setTimeout(resolve, 30));
    assert.ok(document.querySelector('.reply-record-ids').textContent.includes('case-1'));
    button('关闭窗口').click();
    await wait(() => !document.querySelector('[role=dialog]'));
    button('选择裁判并重跑').click();
    await wait(() => field('统一模型裁判'));
    assert.equal(field('统一模型裁判').closest('details').open, true);
    assert.equal(field('统一模型裁判').value, '');
    assert.equal(document.querySelector('.lab-consent input').checked, false);
    assert.equal(button('开始评测').disabled, true);
    assert.ok(document.querySelector('[role=dialog]').textContent.includes('不会给旧回复补写分数'));
    fill(field('统一模型裁判'), 'fixture-connection');
    await wait(() => field('统一模型裁判').value === 'fixture-connection');
    assert.equal(button('开始评测').disabled, true);
    document.querySelector('.lab-consent input').click();
    await wait(() => !button('开始评测').disabled);
    fill(field('统一模型裁判'), '');
    await wait(() => button('开始评测').disabled);
    assert.equal(document.querySelector('.lab-consent input').checked, false);
    button('取消', document.querySelector('[role=dialog]')).click();
    await wait(() => !document.querySelector('[role=dialog]'));
    run.results = Array.from({ length: 25 }, (_, index) => ({ ...baseRow, caseId: `case-${index}` }));
    run.caseIds = run.results.map(row => row.caseId);
    run.completed = 25;
    run.total = 25;
    await wait(() => tableRows().length === 20);
    assert.ok(document.querySelector('.reply-results-counts').textContent.includes('25 条执行结果'));
    button('下一页', document.querySelector('.reply-results')).click();
    await wait(() => tableRows().length === 5);
    assert.ok(tableRows()[0].textContent.includes('案例 021'));
    fill(field('搜索答复、模型或案例编号'), 'case-24');
    await wait(() => tableRows().length === 1);
    assert.ok(tableRows()[0].textContent.includes('案例 025'));
    assert.ok(document.querySelector('.reply-results .pagination').textContent.includes('第 1 / 1 页'));
    assert.deepEqual(errors, []);
    assert.ok(calls.length > 0);
    console.log('PASS: quality-first results, score evidence, neutral labels, filters, no fabricated grades, XSS escaping, case retry, stale-response isolation, explicit judge and consent gates; no inference calls');
  } finally { window.close(); }
}
check().catch(error => { console.error(error); process.exitCode = 1; });
