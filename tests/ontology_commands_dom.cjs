const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const { spawn } = require('node:child_process');
const { createRequire } = require('node:module');
const project = path.resolve(__dirname, '..');
const esbuild = require(project + '/node_modules/esbuild');
const { JSDOM, VirtualConsole } = createRequire(path.resolve(process.env.JSDOM_PACKAGE_ROOT, 'package.json'))('jsdom');

async function check() {
  const directory = await fs.mkdtemp('/private/tmp/evalpilot-ontology-command-test-');
  const server = spawn(project + '/.venv/bin/python', [project + '/tests/ontology_command_server.py'], { cwd: project, env: { ...process.env, EVAL_DATA_DIR: directory, PYTHONPYCACHEPREFIX: directory + '/pycache' }, stdio: ['ignore', 'pipe', 'pipe'] });
  let dom;
  try {
    const port = await new Promise((resolve, reject) => { let output = ''; const timer = setTimeout(() => reject(new Error('Test server did not start')), 20000); server.stdout.on('data', chunk => { output += chunk; if (output.includes('\n')) { clearTimeout(timer); resolve(JSON.parse(output.split('\n')[0]).port); } }); server.on('exit', code => { clearTimeout(timer); reject(new Error('Test server exited: ' + code)); }); });
    const base = 'http://127.0.0.1:' + port;
    const endpoint = '/api/support/ontology/workbench/';
    const initial = await (await fetch(base + endpoint + 'state')).json();
    assert.equal((await fetch(base + endpoint + 'command', { method: 'POST', headers: { 'Content-Type': 'text/plain' }, body: '{}' })).status, 415);
    assert.equal((await fetch(base + endpoint + 'command', { method: 'POST', headers: { 'Content-Type': 'application/json', Origin: 'https://untrusted.invalid' }, body: '{}' })).status, 403);
    const built = await esbuild.build({ stdin: { contents: 'import React from "react"; import { createRoot } from "react-dom/client"; import { OntologyWorkspace } from "./src/OntologyWorkspace"; createRoot(document.getElementById("root")).render(<OntologyWorkspace/>);', resolveDir: project, loader: 'tsx' }, bundle: true, write: false, format: 'iife', loader: { '.css': 'empty' }, define: { 'process.env.NODE_ENV': '"production"' } });
    const errors = [], requests = [];
    let lastCommand, lastCommit, slow = false;
    const consoleProxy = new VirtualConsole(); consoleProxy.on('jsdomError', error => errors.push(error.message));
    dom = new JSDOM('<!doctype html><html><body><div id="root"></div></body></html>', { url: base + '/#ontology?mode=example&view=graph', runScripts: 'dangerously', pretendToBeVisual: true, virtualConsole: consoleProxy });
    const window = dom.window, document = window.document;
    const delay = milliseconds => new Promise(resolve => setTimeout(resolve, milliseconds));
    window.AbortController = global.AbortController;
    window.matchMedia = () => ({ matches: false, addEventListener() {}, removeEventListener() {} });
    window.ResizeObserver = class { observe() {} unobserve() {} disconnect() {} };
    window.scrollTo = () => {}; window.HTMLElement.prototype.scrollIntoView = () => {};
    window.HTMLCanvasElement.prototype.getContext = () => ({ clearRect() {}, setTransform() {}, setLineDash() {}, beginPath() {}, moveTo() {}, lineTo() {}, stroke() {}, fill() {}, fillRect() {}, strokeRect() {}, arc() {}, fillText() {}, measureText(text) { return { width: [...text].length * 12 }; } });
    window.fetch = async (input, options) => {
      const target = new URL(input, base); assert.equal(target.origin, base);
      assert.ok(target.pathname.startsWith('/api/support/ontology/'));
      const method = options?.method || 'GET';
      assert.ok(method === 'GET' || [endpoint + 'command', endpoint + 'commit', '/api/support/ontology/business/run', '/api/support/ontology/business/verify'].includes(target.pathname));
      requests.push({ path: target.pathname, method });
      const response = await fetch(target, options);
      if (target.pathname === endpoint + 'command') { lastCommand = await response.clone().json(); if (slow) await delay(500); }
      if (target.pathname === endpoint + 'commit') lastCommit = await response.clone().json();
      return response;
    };
    const wait = async predicate => { const deadline = Date.now() + 25000; while (Date.now() < deadline) { assert.deepEqual(errors, []); if (predicate()) return; await delay(40); } throw new Error('Timed out: ' + predicate.toString()); };
    const visible = element => !element.closest('[hidden]');
    const button = (name, root = document) => [...root.querySelectorAll('button')].find(element => visible(element) && (element.textContent.trim() === name || element.getAttribute('aria-label') === name));
    const click = async (name, root = document) => { await wait(() => button(name, root)); assert.equal(button(name, root).disabled, false, name); button(name, root).click(); await delay(65); };
    const field = label => document.querySelector(`[aria-label="${label}"]`);
    const fill = async (element, value) => { const prototype = element.tagName === 'INPUT' ? window.HTMLInputElement.prototype : window.HTMLTextAreaElement.prototype; Object.getOwnPropertyDescriptor(prototype, 'value').set.call(element, value); element.dispatchEvent(new window.Event('input', { bubbles: true })); await delay(65); };
    const command = async text => { await fill(field('图谱业务指令'), text); await click('发送指令'); await wait(() => button('发送指令') && !button('刷新操作记录').disabled); };
    const apply = async () => { await click('确认执行本次修改'); await wait(() => document.querySelector('.oc-notice')?.textContent.includes('图谱已刷新')); };
    const select = async label => { if (document.querySelector('.ontology-browser').hidden) await click('元素目录'); await fill(field('搜索图谱元素'), label); await click('查看元素：' + label); };
    window.eval(built.outputFiles[0].text);
    await wait(() => document.querySelector('.ontology-studio'));
    if (document.querySelector('.ontology-inspector').hidden) await click('元素与证据');
    await click('业务指令');
    await wait(() => button('发送指令') && !button('刷新操作记录').disabled && document.querySelector('.oc-welcome'));
    assert.equal(button('业务指令').getAttribute('aria-pressed'), 'true');
    assert.equal(document.querySelectorAll('.oc-event').length, 0);
    await select('启动异常');
    assert.match(document.querySelector('.oc-context').textContent, /启动异常/);
    await command('运行客服任务“我的主机启动没反应。”');
    assert.deepEqual(lastCommand.output.comparison.selected, []);
    await command('添加别名“启动没反应”');
    assert.equal(lastCommand.function, 'add_alias');
    assert.equal(lastCommand.writesApplied, false);
    assert.equal((await (await fetch(base + endpoint + 'state')).json()).revision, initial.revision);
    assert.ok(button('确认执行本次修改'));
    await select('整机');
    assert.equal(button('确认执行本次修改'), undefined);
    await command('给“启动异常”添加别名“启动没反应”');
    await apply();
    assert.equal(lastCommit.status, 'committed');
    assert.ok(document.querySelector('[aria-label="查看元素：启动没反应"]'));
    assert.match(document.querySelector('.oc-context').textContent, /启动异常/);
    await command('运行客服任务“我的主机启动没反应。”');
    assert.equal(lastCommand.output.comparison.selected[0].id, 'DEMO-STARTUP');
    assert.match(document.querySelector('.oc-event:last-child').textContent, /DEMO-STARTUP/);
    await click('定位这次执行关系', document.querySelector('.oc-event:last-child'));
    await wait(() => document.querySelector('.ontology-business-evidence'));
    assert.ok(document.querySelector('canvas,.ontology-object-svg').getAttribute('aria-label').includes('当前'));
    await command('运行固定验收');
    assert.equal(lastCommand.output.passed, 12);
    await select('启动异常');
    await command('说明改为“本机更新后的匿名说明。”'); await apply();
    assert.match(document.querySelector('.oc-context').textContent, /本机更新后的匿名说明/);
    await command('新增部件“散热模组”'); await apply();
    assert.match(document.querySelector('.oc-context').textContent, /散热模组/);
    await select('整机');
    await command('关联“散热模组”，关系“示例组成部件”'); await apply();
    await command('查看关联元素');
    assert.ok(lastCommand.output.relations.some(relation => relation.target.startsWith('custom:') && relation.type === 'has_component'));
    await select('启动异常');
    await command('关联“主控板”，关系“候选部件”');
    assert.match(document.querySelector('.oc-error').textContent, /概念范围/);
    assert.equal(button('确认执行本次修改'), undefined);
    await select('E102 · A-100');
    await command('关联“供电模块”，关系“候选部件”');
    assert.equal(lastCommand.status, 'blocked');
    assert.equal(button('确认执行本次修改'), undefined);
    await command('撤销上次修改'); await apply();
    const stateAfter = await (await fetch(base + endpoint + 'state')).json();
    assert.ok(stateAfter.history.some(item => item.status === 'committed' && item.function === 'undo_change'));
    await click('刷新图谱'); await wait(() => button('发送指令') && !button('刷新操作记录').disabled);
    assert.ok(document.querySelectorAll('.oc-event.committed').length > 0);
    await click('全屏展示');
    await click('元素与证据', document.querySelector('.ontology-fullscreen-controls'));
    if (document.querySelector('.ontology-inspector').hidden) await click('元素与证据', document.querySelector('.ontology-fullscreen-controls'));
    await command('运行固定验收'); assert.equal(lastCommand.output.passed, 12);
    await click('退出全屏');
    slow = true;
    await fill(field('图谱业务指令'), '给“启动异常”添加别名“等待中的叫法”'); await click('发送指令');
    await select('整机'); await delay(750);
    assert.equal(button('确认执行本次修改'), undefined);
    assert.match(document.querySelector('.oc-notice').textContent, /对象已变化/);
    slow = false;
    await command('删除全部真实客服数据');
    assert.match(document.querySelector('.oc-error').textContent, /没有执行/);
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({ passed: true, checks: ['selected node context', 'preview before confirmation', 'actual durable alias and retrieval change', 'schema description mutation', 'entity creation and typed relationships', 'invalid relationship blocked', 'regression failure blocks write', 'persisted audit and undo', 'reload restores history', 'fullscreen command interaction', 'target change cancels confirmation', 'arbitrary commands rejected', 'JSON and origin gates'], realDatasetWrites: false, testWorkspaceWrites: true, externalModelCalls: false, visualVerification: false, requests: requests.length }));
  } finally { dom?.window.close(); server.kill('SIGTERM'); await new Promise(resolve => server.exitCode !== null ? resolve() : server.once('exit', resolve)); await fs.rm(directory, { recursive: true, force: true }); }
}

check().catch(error => { console.error(error); process.exitCode = 1; });
