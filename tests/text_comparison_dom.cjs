const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const { createRequire } = require('node:module');
const project = path.resolve(__dirname, '..');
const esbuild = require(project + '/node_modules/esbuild');
const dependency = createRequire(path.resolve(process.env.JSDOM_PACKAGE_ROOT, 'package.json'));
const { JSDOM, VirtualConsole } = dependency('jsdom');

async function check() {
  const base = process.env.EVAL_BROWSER_BASE || 'http://127.0.0.1:4292';
  const readonly = process.env.EVAL_READONLY === '1';
  const initialRun = process.env.EVAL_COMPARISON_START_RUN || '';
  if (!readonly && !base.endsWith(':4292')) throw new Error('Mutation tests require the isolated comparison fixture on port 4292');
  const built = await esbuild.build({ entryPoints: [project + '/src/main.tsx'], bundle: true, write: false, format: 'iife', loader: { '.css': 'empty' }, plugins: [{ name: 'raw-docs', setup(build) { build.onResolve({ filter: /\?raw$/ }, args => ({ path: path.resolve(args.resolveDir, args.path.replace(/\?raw$/, '')), namespace: 'raw-docs' })); build.onLoad({ filter: /.*/, namespace: 'raw-docs' }, async args => ({ contents: await fs.readFile(args.path, 'utf8'), loader: 'text' })); } }], define: { 'process.env.NODE_ENV': '"production"' } });
  const errors = [];
  const calls = [];
  const proxy = new VirtualConsole();
  proxy.on('jsdomError', error => errors.push(error.message));
  const dom = new JSDOM('<!doctype html><html><body><div id="root"></div></body></html>', { url: base + '/#compare' + (initialRun ? `?run=${encodeURIComponent(initialRun)}` : ''), runScripts: 'dangerously', pretendToBeVisual: true, virtualConsole: proxy });
  const window = dom.window;
  window.AbortController = global.AbortController;
  window.AbortSignal = global.AbortSignal;
  window.fetch = (input, options) => { const target = new URL(input, base); if (target.origin !== base) throw new Error('External network prohibited'); if (options?.method === 'POST') { if (readonly) throw new Error('Mutations forbidden in read-only mode'); calls.push({ path: target.pathname, body: target.pathname.endsWith('/connections') ? { redacted: true } : JSON.parse(options.body) }); } return fetch(target, options); };
  window.matchMedia = () => ({ matches: false, addEventListener() {}, removeEventListener() {} });
  window.ResizeObserver = class { observe() {} unobserve() {} disconnect() {} };
  window.scrollTo = () => {};
  window.HTMLElement.prototype.scrollIntoView = () => {};
  window.eval(built.outputFiles[0].text);
  const document = window.document;
  const wait = async predicate => { const deadline = Date.now() + 30000; while (Date.now() < deadline) { const result = predicate(); if (result) return result; await new Promise(resolve => setTimeout(resolve, 70)); } throw new Error('Timed out: ' + predicate.toString()); };
  const button = (name, root = document) => [...root.querySelectorAll('button')].find(element => element.textContent.trim() === name || element.getAttribute('aria-label') === name);
  const click = async (name, root = document) => { const element = await wait(() => button(name, root)); assert.equal(element.disabled, false, name); element.click(); await new Promise(resolve => setTimeout(resolve, 100)); };
  const fill = (element, value) => { assert.ok(element); const prototype = element.tagName === 'SELECT' ? window.HTMLSelectElement.prototype : window.HTMLInputElement.prototype; Object.getOwnPropertyDescriptor(prototype, 'value').set.call(element, value); element.dispatchEvent(new window.Event(element.tagName === 'SELECT' ? 'change' : 'input', { bubbles: true })); };
  const field = label => document.querySelector(`[aria-label="${label}"]`);
  const dialog = () => document.querySelector('[role="dialog"]');
  const dialogField = label => [...dialog().querySelectorAll('label')].find(element => element.textContent.startsWith(label))?.querySelector('input,select');
  const state = async () => (await fetch(base + '/api/support/lab/state')).json();
  const pressedMode = title => [...document.querySelectorAll('.lab-comparison-mode button')].find(element => element.querySelector('strong').textContent === title)?.getAttribute('aria-pressed') === 'true';
  const expectedMode = run => run.comparisonMode === 'vertical' || (!run.comparisonMode && run.models.length >= 2 && run.models.every(model => model.provider === run.models[0].provider && model.family === run.models[0].family)) ? '版本迭代对比' : '跨模型对比';
  const expectRunResults = async run => {
    await wait(() => button('查看已有结果')?.getAttribute('aria-pressed') === 'true' && field('对比基线')?.value.startsWith(run.id + '|') && pressedMode(expectedMode(run)));
    if (run.models.length === 2) assert.ok(field('对比候选').value.startsWith(run.id + '|'));
  };
  const checkHistoricalNavigation = async run => {
    window.location.hash = `benchmark?run=${run.id}`;
    const link = await wait(() => [...document.querySelectorAll('a')].find(element => element.textContent.trim() === '对比本批版本'));
    assert.ok(link.hash.includes('panel=results'));
    link.click();
    await expectRunResults(run);
    window.location.hash = `compare?mode=text&run=${run.id}`;
    await expectRunResults(run);
    window.location.hash = `compare?run=${run.id}&comparison=horizontal`;
    await wait(() => pressedMode('跨模型对比') && button('查看已有结果')?.getAttribute('aria-pressed') === 'true');
    window.location.hash = `compare?run=${run.id}&comparison=vertical&panel=setup`;
    await wait(() => pressedMode('版本迭代对比') && button('新建同批对比')?.getAttribute('aria-pressed') === 'true');
    window.history.back();
    await wait(() => window.location.hash === `#compare?run=${run.id}&comparison=horizontal` && pressedMode('跨模型对比') && button('查看已有结果')?.getAttribute('aria-pressed') === 'true');
    window.location.hash = `compare?run=${run.id}&project=unknown-project-fixture`;
    await wait(() => !field('对比基线') && document.querySelector('.agent-lab')?.textContent.includes('先从真实售后数据训练'));
    window.location.hash = `compare?run=${run.id}`;
    await expectRunResults(run);
    window.location.hash = 'compare?mode=text';
    await wait(() => button('新建同批对比')?.getAttribute('aria-pressed') === 'true' && pressedMode('跨模型对比'));
  };
  const chooseMode = async title => { const element = [...document.querySelectorAll('.lab-comparison-mode button')].find(item => item.querySelector('strong').textContent === title); element.click(); await new Promise(resolve => setTimeout(resolve, 100)); };
  const createConnection = async (target, provider, name, family, model, shouldFail = false) => {
    await click(target);
    await wait(() => dialog()?.querySelector('input[type="password"]'));
    assert.equal(dialog().querySelectorAll('input[type="password"]').length, 1);
    fill(dialogField('官方服务'), provider);
    fill(dialogField('版本显示名称'), name);
    fill(dialogField('模型系列'), family);
    fill(dialogField('候选模型名称'), model);
    fill(dialogField('API Key'), 'unit-test-placeholder-only');
    dialog().querySelector('input[type="checkbox"]').click();
    await wait(() => !button('保存内存配置', dialog()).disabled);
    await click('保存内存配置', dialog());
    await wait(() => dialog()?.querySelector('.lab-connection-test'));
    assert.equal(dialogField('API Key').value, '');
    assert.equal(dialogField('候选模型名称').disabled, true);
    assert.equal(button('完成并选用此模型', dialog()).disabled, true);
    assert.equal(button('测试文字连接', dialog()).disabled, true);
    dialog().querySelector('.lab-connection-test input').click();
    await wait(() => !button('测试文字连接', dialog()).disabled);
    await click('测试文字连接', dialog());
    if (shouldFail) {
      await wait(() => dialog()?.querySelector('[role="status"]')?.textContent.includes('连接失败'));
      assert.equal(button('完成并选用此模型', dialog()).disabled, true);
      await click('关闭', dialog());
      return;
    }
    await wait(() => !button('完成并选用此模型', dialog()).disabled);
    await click('完成并选用此模型', dialog());
    await wait(() => !dialog());
  };
  try {
    if (initialRun) {
      const historical = await (await fetch(base + '/api/support/lab/runs/' + encodeURIComponent(initialRun))).json();
      await expectRunResults(historical);
      window.location.hash = 'compare?mode=text';
      await wait(() => button('新建同批对比')?.getAttribute('aria-pressed') === 'true');
    }
    await wait(() => field('选择模型 A'));
    assert.ok(button('添加模型 / 输入 Key'));
    assert.equal(button('新建同批对比').getAttribute('aria-pressed'), 'true');
    assert.equal(button('开始同批对比').disabled, true);
    assert.ok(field('选择模型 A').options.length >= 3);
    await click('查看已有结果');
    assert.ok(button('选择模型并新建对比'));
    assert.ok(field('对比候选'));
    await click('选择模型并新建对比');
    await click('先用两个本地版本体验');
    await wait(() => field('选择模型 A').value && field('选择模型 B').value && !button('开始同批对比').disabled);
    assert.notEqual(field('选择模型 A').value, field('选择模型 B').value);
    const baseline = field('选择模型 A').value;
    assert.equal([...field('选择模型 B').options].find(option => option.value === baseline).disabled, true);
    if (readonly) {
      await click('添加候选模型');
      await wait(() => dialog()?.querySelector('input[type="password"]'));
      assert.equal(dialog().querySelectorAll('input[type="password"]').length, 1);
      assert.equal(button('保存内存配置', dialog()).disabled, true);
      await click('关闭', dialog());
      const historical = (await state()).runs.find(run => run.status === 'completed' && run.models.length === 2);
      assert.ok(historical);
      await checkHistoricalNavigation(historical);
      assert.equal(calls.length, 0);
      assert.deepEqual(errors, []);
      console.log(JSON.stringify({ passed: true, readonly, directBatchLink: !!initialRun, checks: ['model A and B controls', 'local pair quick selection', 'historical results separated', 'add connection opens password modal', 'batch link and legacy link', 'same-page mode and panel navigation', 'browser back', 'project isolation', 'bare comparison returns to setup', 'no model calls'], layoutVerified: false }));
      return;
    }
    fill(field('同批对比案例数量'), '1');
    await wait(() => button('开始同批对比').disabled);
    fill(field('同批对比案例数量'), '3');
    await wait(() => !button('开始同批对比').disabled);
    await click('开始同批对比');
    await wait(() => window.location.hash.includes('panel=results') && field('对比候选')?.value);
    await click('查看对比结果');
    await wait(() => document.querySelector('.lab-kpis'));
    const local = (await state()).runs[0];
    assert.equal(local.total, 6);
    assert.equal(local.comparisonMode, 'vertical');
    assert.equal(local.metrics[local.models[0].id].completed, 3);
    assert.equal(local.metrics[local.models[1].id].completed, 3);
    await click('新建同批对比');
    await chooseMode('跨模型对比');
    await createConnection('添加候选模型', 'deepseek', '失败连接测试', '不可用系列', 'unavailable-fixture', true);
    assert.equal(calls.filter(call => call.path.endsWith('/runs')).length, 1);
    const broken = (await state()).connections.find(connection => connection.model === 'unavailable-fixture');
    fill(field('选择模型 B'), broken.id);
    await wait(() => document.querySelector('.text-comparison-start').textContent.includes('尚不可用'));
    assert.equal(button('开始同批对比').disabled, true);
    await createConnection('添加基线模型', 'openai', '隔离模型甲', '同名系列', 'candidate-fixture-one');
    await createConnection('添加候选模型', 'anthropic', '隔离模型乙', '同名系列', 'candidate-fixture-two');
    await wait(() => field('选择模型 A').value && field('选择模型 B').value);
    const configured = await state();
    const firstConnection = configured.connections.find(connection => connection.name === '隔离模型甲');
    const secondConnection = configured.connections.find(connection => connection.name === '隔离模型乙');
    assert.equal(field('选择模型 A').value, firstConnection.id);
    assert.equal(field('选择模型 B').value, secondConnection.id);
    assert.ok(document.querySelector('.lab-consent').textContent.includes('api.openai.com'));
    assert.ok(document.querySelector('.lab-consent').textContent.includes('api.anthropic.com'));
    fill(field('对比案例来源'), local.id);
    await wait(() => field('同批对比案例数量').max === '3' && !field('同批对比案例数量').disabled);
    fill(field('同批对比案例数量'), '2');
    await wait(() => document.querySelector('.text-comparison-cases').textContent.includes('子集'));
    assert.equal(button('开始同批对比').disabled, true);
    field('同意本次对比外发与费用').click();
    await wait(() => !button('开始同批对比').disabled);
    fill(field('同批对比案例数量'), '3');
    await wait(() => !field('同意本次对比外发与费用').checked);
    fill(field('对比统一裁判'), firstConnection.id);
    await wait(() => document.querySelector('.lab-consent').textContent.includes('最多 12 次'));
    field('同意本次对比外发与费用').click();
    await wait(() => !button('开始同批对比').disabled);
    await click('开始同批对比');
    await wait(() => field('对比基线')?.value.includes((calls.filter(call => call.path.endsWith('/runs')).length > 1 ? 'EVAL-' : 'never')) && !button('查看对比结果').disabled && window.location.hash.includes('comparison=horizontal'));
    await click('查看对比结果');
    await wait(() => document.querySelector('.lab-kpis'));
    const cross = (await state()).runs[0];
    assert.equal(cross.comparisonMode, 'horizontal');
    assert.equal(cross.parentRunId, local.id);
    assert.equal(cross.caseHash, local.caseHash);
    assert.equal(cross.judgeId, firstConnection.id);
    assert.deepEqual(new Set(cross.models.map(version => version.provider)), new Set(['openai', 'anthropic']));
    const details = await (await fetch(base + '/api/support/lab/runs/' + cross.id)).json();
    assert.equal(details.results.length, 6);
    assert.equal(details.results.every(row => row.status === 'completed' && row.traceId && row.judgment), true);
    assert.deepEqual(details.results.filter(row => row.versionId === cross.models[0].id).map(row => row.caseId), details.results.filter(row => row.versionId === cross.models[1].id).map(row => row.caseId));
    assert.equal(JSON.stringify(await state()).includes('unit-test-placeholder-only'), false);
    for (const storage of [window.sessionStorage, window.localStorage]) assert.equal(JSON.stringify(Object.entries(storage)).includes('unit-test-placeholder-only'), false);
    await click('新建同批对比');
    fill(field('选择模型 A'), firstConnection.id);
    await chooseMode('版本迭代对比');
    await createConnection('添加候选模型', 'openai', '隔离模型甲第二版', '同名系列', 'candidate-fixture-three');
    fill(field('同批对比案例数量'), '2');
    await wait(() => field('同意本次对比外发与费用'));
    field('同意本次对比外发与费用').click();
    await wait(() => !button('开始同批对比').disabled);
    await click('开始同批对比');
    await wait(() => window.location.hash.includes('comparison=vertical') && field('对比候选')?.value && !button('查看对比结果').disabled);
    await click('查看对比结果');
    await wait(() => document.querySelector('.lab-kpis'));
    const versionRun = (await state()).runs[0];
    assert.equal(versionRun.comparisonMode, 'vertical');
    assert.equal(versionRun.total, 4);
    assert.equal(versionRun.models.every(model => model.provider === 'openai'), true);
    assert.notEqual(versionRun.models[0].id, versionRun.models[1].id);
    assert.equal((await state()).runs.find(run => run.id === local.id).total, 6);
    await checkHistoricalNavigation(local);
    await checkHistoricalNavigation(cross);
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({ passed: true, readonly, checks: ['local same-batch comparison', 'failed connection disabled', 'new connection save/test/use', 'two provider A/B choices', 'same-provider two versions', 'shared judge and consent reset', 'frozen parent case reuse', 'actual trace creation', 'password not echoed or stored in browser', 'vertical and horizontal historical batch links', 'same-page mode and panel navigation', 'browser back', 'project isolation'], externalCalls: false, providerResponses: 'isolated local test doubles, not real model scores', layoutVerified: false }));
  } finally { window.close(); }
}
check().catch(error => { console.error(error); process.exitCode = 1; });
