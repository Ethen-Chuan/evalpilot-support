const assert = require('node:assert/strict');
const path = require('node:path');
const { createRequire } = require('node:module');
const { createFixture } = require('./modelops-fixture.cjs');
const project = path.resolve(__dirname, '..');
const esbuild = require(project + '/node_modules/esbuild');
const dependency = createRequire(path.resolve(process.env.JSDOM_PACKAGE_ROOT, 'package.json'));
const { JSDOM, VirtualConsole } = dependency('jsdom');

async function check() {
  const built = await esbuild.build({ stdin: { contents: "import React from 'react'; import {createRoot} from 'react-dom/client'; import {ModelOps} from './src/ModelOps'; createRoot(document.getElementById('root')).render(<ModelOps corpora={window.fixtureCorpora}/>);", resolveDir: project, loader: 'tsx' }, bundle: true, write: false, format: 'iife', loader: { '.css': 'empty' }, define: { 'process.env.NODE_ENV': '"production"' } });
  const fixture = createFixture();
  const errors = [];
  const requests = [];
  const proxy = new VirtualConsole();
  proxy.on('jsdomError', error => errors.push(error.message));
  const dom = new JSDOM('<!doctype html><html><body><div id="root"></div></body></html>', { url: 'http://127.0.0.1:4296/#modelops?project=project-a', runScripts: 'dangerously', pretendToBeVisual: true, virtualConsole: proxy });
  const window = dom.window;
  const document = window.document;
  let failState = false;
  let failDetail = false;
  let resolveSlow;
  let slow = false;
  window.fixtureCorpora = fixture.corpora;
  window.AbortController = global.AbortController;
  window.AbortSignal = global.AbortSignal;
  window.fetch = async (input, options) => {
    const target = new URL(input, window.location.href);
    assert.equal(target.origin, window.location.origin);
    assert.ok(!options?.method || options.method === 'GET', 'No mutations or paid inference allowed');
    requests.push(target.pathname);
    if (target.pathname.endsWith('/services')) return new Response(JSON.stringify([{ id: 'fixture', name: '隔离测试服务', endpoint: 'https://example.invalid', discovery: false }]));
    if (target.pathname === '/api/support/lab/state') return new Response(JSON.stringify(fixture.state), { status: failState ? 503 : 200 });
    assert.ok(target.pathname.startsWith('/api/support/lab/runs/'), 'Legacy sandbox must not be called');
    const identifier = decodeURIComponent(target.pathname.split('/').at(-1));
    if (slow && identifier === 'EVAL-OLD') return new Promise(resolve => { resolveSlow = () => resolve(new Response(JSON.stringify(fixture.runs[identifier]))); });
    return new Response(JSON.stringify(fixture.runs[identifier] || {}), { status: failDetail ? 503 : fixture.runs[identifier] ? 200 : 404 });
  };
  window.matchMedia = () => ({ matches: false, addEventListener() {}, removeEventListener() {} });
  window.ResizeObserver = class { observe() {} unobserve() {} disconnect() {} };
  window.scrollTo = () => {};
  window.eval(built.outputFiles[0].text);
  const wait = async predicate => { const deadline = Date.now() + 10000; while (Date.now() < deadline) { if (predicate()) return; await new Promise(resolve => setTimeout(resolve, 25)); } throw new Error('Timed out: ' + predicate.toString()); };
  const text = () => document.body.textContent;
  const button = name => [...document.querySelectorAll('button')].find(element => element.textContent.trim() === name);
  const field = name => document.querySelector(`[aria-label="${name}"]`);
  const metrics = () => [...document.querySelectorAll('.ops-metrics strong')].map(element => element.textContent.trim());
  const fill = (element, value) => { const prototype = element.tagName === 'SELECT' ? window.HTMLSelectElement.prototype : window.HTMLInputElement.prototype; Object.getOwnPropertyDescriptor(prototype, 'value').set.call(element, value); element.dispatchEvent(new window.Event(element.tagName === 'SELECT' ? 'change' : 'input', { bubbles: true })); };
  try {
    await wait(() => metrics().length === 4);
    assert.ok(text().includes('售后客服模型运营'));
    assert.ok(!/车辆|座舱|创建演示空间|晋级稳定|不调用外部模型/.test(text()));
    assert.deepEqual(metrics(), ['2 / 6', '1', '50.0%', '2']);
    assert.equal(document.querySelectorAll('.ops-table tbody tr').length, 2);
    assert.ok(document.querySelector('.ops-table').textContent.includes('50.0%'));
    assert.ok(document.querySelector('.ops-table').textContent.includes('未报告'));
    assert.ok(text().includes('自评偏差'));
    assert.equal(document.querySelectorAll('.ops-evidence').length, 3);
    assert.ok(!field('运营评测批次').textContent.includes('EVAL-LOCAL'));
    assert.ok(!field('运营评测批次').textContent.includes('EVAL-OTHER'));
    for (const anchor of document.querySelectorAll('.ops-evidence footer a')) {
      assert.equal(new URLSearchParams(anchor.hash.split('?')[1]).get('run'), 'EVAL-MIXED');
      assert.equal(new URLSearchParams(anchor.hash.split('?')[1]).get('project'), 'project-a');
    }
    [...document.querySelectorAll('.ops-filters button')].find(element => element.textContent.startsWith('执行失败')).click();
    await wait(() => document.querySelectorAll('.ops-evidence').length === 1);
    assert.ok(document.querySelector('.ops-evidence').textContent.includes('执行失败'));
    [...document.querySelectorAll('.ops-filters button')].find(element => element.textContent.startsWith('全部记录')).click();
    fill(field('搜索模型、会话编号或答复'), '不可能存在的测试字符串');
    await wait(() => document.querySelectorAll('.ops-evidence').length === 0);
    fill(field('搜索模型、会话编号或答复'), '');
    await wait(() => document.querySelectorAll('.ops-evidence').length === 3);
    button('添加模型').click();
    await wait(() => document.querySelector('[role=dialog]'));
    assert.equal(field('API Key').type, 'password');
    assert.equal(field('API Key').value, '');
    button('关闭').click();
    await wait(() => !document.querySelector('[role=dialog]'));
    button('管理连接').click();
    await wait(() => document.querySelector('[role=dialog]'));
    assert.equal(field('API Key').value, '');
    assert.equal(field('候选模型名称').value, 'fixture-model-a');
    button('关闭').click();
    fill(field('历史批次编号'), 'EVAL-OLD');
    await wait(() => !button('查找记录').disabled);
    button('查找记录').click();
    await wait(() => field('运营评测批次')?.value === 'EVAL-OLD');
    assert.deepEqual(metrics(), ['2 / 2', '0', '100.0%', '0']);
    window.location.hash = '#modelops?project=project-a&run=EVAL-MISSING';
    await wait(() => text().includes('指定批次不存在'));
    assert.equal(metrics().length, 0);
    window.location.hash = '#modelops?project=project-a&run=EVAL-OTHER';
    await wait(() => text().includes('该批次不属于当前项目'));
    assert.equal(metrics().length, 0);
    window.location.hash = '#modelops?project=project-a&run=EVAL-LOCAL';
    await wait(() => text().includes('这是本地基线批次'));
    assert.equal(metrics().length, 0);
    window.location.hash = '#modelops?project=missing';
    await wait(() => text().includes('项目不可用'));
    assert.equal(metrics().length, 0);
    assert.equal(button('新建客服评测').disabled, true);
    window.location.hash = '#modelops?project=project-empty';
    await wait(() => text().includes('当前项目还没有外部模型评测记录'));
    assert.equal(metrics().length, 0);
    window.location.hash = '#modelops?run=EVAL-OTHER';
    await wait(() => field('运营项目')?.value === 'project-b');
    assert.deepEqual(metrics(), ['2 / 2', '0', '100.0%', '0']);
    slow = true;
    window.location.hash = '#modelops?project=project-a&run=EVAL-OLD';
    await wait(() => resolveSlow);
    window.location.hash = '#modelops?project=project-b';
    await wait(() => field('运营评测批次')?.value === 'EVAL-OTHER');
    resolveSlow();
    await new Promise(resolve => setTimeout(resolve, 60));
    assert.equal(field('运营项目').value, 'project-b');
    assert.equal(field('运营评测批次').value, 'EVAL-OTHER');
    slow = false;
    failDetail = true;
    button('刷新记录').click();
    await wait(() => text().includes('本批详情暂时无法读取'));
    assert.equal(metrics().length, 0);
    failDetail = false;
    button('刷新记录').click();
    await wait(() => metrics().length === 4);
    failState = true;
    button('刷新记录').click();
    await wait(() => text().includes('已隐藏旧数据'));
    assert.equal(metrics().length, 0);
    failState = false;
    button('刷新记录').click();
    await wait(() => metrics().length === 4);
    fixture.runs['EVAL-OTHER'].results = [];
    fixture.runs['EVAL-OTHER'].metrics = {};
    await wait(() => metrics()[0] === '0 / 2');
    assert.equal(metrics()[2], '未测');
    assert.ok(!document.querySelector('.ops-table').textContent.includes('100.0%'));
    assert.ok(requests.every(request => request.startsWith('/api/support/lab/')));
    assert.deepEqual(errors, []);
    console.log('PASS: aftersales domain, actual batch metrics, local exclusion, failure and judge filters, search, safe connection modal, exact evidence links, old run lookup, project isolation, empty/missing results, race protection, error recovery, read-only polling');
  } finally { window.close(); }
}

check().catch(error => { console.error(error); process.exitCode = 1; });
