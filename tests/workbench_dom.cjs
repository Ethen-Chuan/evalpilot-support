const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const { createRequire } = require('node:module');
const project = path.resolve(__dirname, '..');
const esbuild = require(project + '/node_modules/esbuild');
const { JSDOM, VirtualConsole } = createRequire(path.resolve(process.env.JSDOM_PACKAGE_ROOT, 'package.json'))('jsdom');

async function check() {
  const base = process.env.EVAL_ONTOLOGY_BASE || 'http://127.0.0.1:4294';
  assert.match(base, /^http:\/\/127\.0\.0\.1:\d+$/);
  const built = await esbuild.build({ entryPoints: [project + '/src/main.tsx'], bundle: true, write: false, format: 'iife', loader: { '.css': 'empty' }, plugins: [{ name: 'raw-docs', setup(build) { build.onResolve({ filter: /\?raw$/ }, args => ({ path: path.resolve(args.resolveDir, args.path.replace(/\?raw$/, '')), namespace: 'raw-docs' })); build.onLoad({ filter: /.*/, namespace: 'raw-docs' }, async args => ({ contents: await fs.readFile(args.path, 'utf8'), loader: 'text' })); } }], define: { 'process.env.NODE_ENV': '"production"' } });
  const errors = [], visited = [], requests = [];
  const proxy = new VirtualConsole(); proxy.on('jsdomError', error => errors.push(error.message));
  const dom = new JSDOM('<!doctype html><html><body><div id="root"></div></body></html>', { url: base + '/#datasets', runScripts: 'dangerously', pretendToBeVisual: true, virtualConsole: proxy });
  const window = dom.window, document = window.document;
  const delay = milliseconds => new Promise(resolve => setTimeout(resolve, milliseconds));
  Object.defineProperty(window, 'innerWidth', { value: 1440, configurable: true });
  window.AbortController = global.AbortController;
  window.structuredClone = global.structuredClone;
  window.matchMedia = () => ({ matches: false, addEventListener() {}, removeEventListener() {} });
  window.ResizeObserver = class { observe() {} disconnect() {} unobserve() {} };
  window.scrollTo = () => {}; window.HTMLElement.prototype.scrollIntoView = () => {};
  window.HTMLCanvasElement.prototype.getContext = () => ({ clearRect() {}, setTransform() {}, setLineDash() {}, beginPath() {}, moveTo() {}, lineTo() {}, stroke() {}, fill() {}, fillRect() {}, arc() {}, fillText() {}, measureText(text) { return { width: text.length * 12 }; } });
  window.fetch = async (input, options) => {
    const target = new URL(input, base);
    assert.equal(target.origin, base); assert.equal(options?.method || 'GET', 'GET');
    requests.push(target.pathname);
    return fetch(target, options);
  };
  const wait = async predicate => { const deadline = Date.now() + 25000; while (Date.now() < deadline) { assert.deepEqual(errors, []); if (predicate()) return; await delay(50); } throw new Error('Timed out: ' + predicate.toString() + ' route=' + window.location.hash + ' detail=' + document.querySelector('.ontology-node-detail h3')?.textContent + ' selected=' + document.querySelector('[data-object-id][aria-pressed=true]')?.getAttribute('data-object-id')); };
  const button = (name, root = document) => [...root.querySelectorAll('button')].find(element => !element.closest('[hidden]') && (element.textContent.trim() === name || element.getAttribute('aria-label') === name));
  const click = async (name, root = document) => { await wait(() => button(name, root)); assert.equal(button(name, root).disabled, false); button(name, root).click(); await delay(90); };
  const fill = (element, value) => { Object.getOwnPropertyDescriptor(window.HTMLInputElement.prototype, 'value').set.call(element, value); element.dispatchEvent(new window.Event('input', { bubbles: true })); };
  try {
    window.eval(built.outputFiles[0].text);
    await wait(() => document.querySelector('.project-asset-metrics'));
    assert.equal(document.querySelectorAll('.project-workflow-nav a').length, 4);
    assert.equal(Number(document.querySelectorAll('.project-asset-metrics dd')[1].textContent.replaceAll(',', '')), (await (await fetch(base + '/api/support/state')).json()).corpora.reduce((total, corpus) => total + corpus.totals.sessions, 0));
    assert.equal(document.querySelector('[aria-label="主导航"]').querySelectorAll('button').length, 10);
    await click('查找功能'); await wait(() => document.querySelector('.command-results'));
    fill(document.querySelector('[aria-label="输入功能名称"]'), '对话实验'); await delay(70);
    await click('对话实验室', document.querySelector('.command-results'));
    await wait(() => document.querySelector('.simulator'));
    assert.equal(document.querySelector('.modal'), null);
    window.location.hash = '#ontology?mode=example&view=graph';
    await wait(() => document.querySelectorAll('[data-object-id]').length > 3);
    assert.ok(document.querySelector('.workbench-shell').classList.contains('compact-navigation'));
    assert.equal(document.querySelector('.ontology-browser').hidden, true);
    const svg = document.querySelector('.ontology-object-svg');
    const zoom = () => parseInt(document.querySelector('[aria-label="当前缩放"]').textContent, 10);
    assert.ok(zoom() >= 78);
    assert.ok([...document.querySelectorAll('.og-object-name')].some(node => node.textContent === 'E102 · A-100'));
    const count = document.querySelectorAll('[data-object-id]').length;
    const equipment = document.querySelector('[data-object-id="equipment"]');
    equipment.dispatchEvent(new window.KeyboardEvent('keydown', { key: 'Enter', bubbles: true, cancelable: true }));
    await wait(() => document.querySelector('.ontology-node-detail h3')?.textContent === '整机');
    assert.ok(document.querySelectorAll('[data-object-id]').length >= count);
    assert.ok(document.querySelector('.ontology-context-rail').textContent.includes('整机'));
    const positioned = document.querySelector('[data-object-id="equipment"]');
    const before = positioned.getAttribute('transform');
    positioned.dispatchEvent(new window.MouseEvent('pointerdown', { clientX: 100, clientY: 100, bubbles: true }));
    svg.dispatchEvent(new window.MouseEvent('pointermove', { clientX: 165, clientY: 145, bubbles: true }));
    svg.dispatchEvent(new window.MouseEvent('pointerup', { clientX: 165, clientY: 145, bubbles: true }));
    await delay(100); assert.notEqual(positioned.getAttribute('transform'), before);
    const beforePan = svg.querySelector(':scope>g').getAttribute('transform');
    svg.dispatchEvent(new window.MouseEvent('pointerdown', { clientX: 10, clientY: 20, bubbles: true }));
    svg.dispatchEvent(new window.MouseEvent('pointermove', { clientX: 80, clientY: 45, bubbles: true }));
    svg.dispatchEvent(new window.MouseEvent('pointerup', { clientX: 80, clientY: 45, bubbles: true }));
    await delay(100); assert.notEqual(svg.querySelector(':scope>g').getAttribute('transform'), beforePan);
    await click('重新布局并取消固定节点');
    await delay(100); assert.equal(positioned.getAttribute('transform'), before);
    const beforeZoom = zoom(); await click('放大图谱'); assert.ok(zoom() > beforeZoom);
    svg.dispatchEvent(new window.WheelEvent('wheel', { deltaY: 180, clientX: 300, clientY: 200, bubbles: true, cancelable: true }));
    await delay(100); assert.ok(zoom() < beforeZoom * 1.2);
    await click('导航缩略图'); assert.equal(button('导航缩略图').getAttribute('aria-expanded'), 'true');
    const navigator = document.querySelector('[aria-label="重新居中整个图谱"]');
    navigator.dispatchEvent(new window.KeyboardEvent('keydown', { key: 'Enter', bubbles: true, cancelable: true }));
    await click('导航缩略图'); assert.equal(document.querySelector('.og-map'), null);
    await click('业务指令'); await wait(() => document.querySelector('.oc-welcome'));
    await click('带入第一条指令'); assert.ok(document.querySelector('#ontology-command-input').value.includes('启动没反应'));
    assert.equal(document.querySelectorAll('.oc-event').length, 0);
    await click('收起对象面板'); assert.equal(document.querySelector('.ontology-inspector').hidden, true);
    await click('元素目录'); assert.equal(document.querySelector('.ontology-browser').hidden, false);
    await click('收起元素目录'); assert.equal(document.querySelector('.ontology-browser').hidden, true);
    await click('切换深色模式'); assert.equal(document.documentElement.dataset.mode, 'dark');
    assert.equal(JSON.parse(window.localStorage.getItem('evalpilot.appearance.v2')).mode, 'dark');
    await click('切换浅色模式'); assert.equal(document.documentElement.dataset.mode, 'light');
    await click('展开侧边导航'); assert.ok(!document.querySelector('.workbench-shell').classList.contains('compact-navigation'));
    for (const [route, selector] of [['service', '.svc-mission'], ['services', '.svc-editor'], ['releases', '.svc-release-list'], ['improve', '.svc-metrics'], ['benchmark', '.agent-lab'], ['overview', '.cx-dashboard'], ['compare', '.agent-lab'], ['modelops', '.modelops'], ['guide', '.guide-header'], ['traces', '.trace-category-tabs']]) {
      window.location.hash = '#' + route;
      await wait(() => document.querySelector('.workbench-shell')?.dataset.page === route);
      await wait(() => document.querySelector(selector) && document.querySelector('.main-content').textContent.trim().length > 80);
      assert.ok(!document.querySelector('.fatal-error'));
      assert.ok(document.querySelector('.main-content').textContent.trim().length > 80);
      visited.push({ route, mounted: !!document.querySelector(selector) });
    }
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({ passed: true, visited, checks: ['navigation and search', 'asset counts from API', 'readable default zoom', 'code/model names intact', 'keyboard selection expands actual graph', 'SVG node dragging and camera panning', 'zoom and navigation map', 'command templates do not write', 'panel toggles', 'persisted light/dark selection', 'compact navigation'], requests: requests.length, externalCalls: false, writes: false, browserVisualVerification: false }));
  } finally { window.close(); }
}
check().catch(error => { console.error(error); process.exitCode = 1; });
